const languageButton = document.getElementById('langToggle');
const description = document.querySelector('meta[name="description"]');
const savedLanguage = localStorage.getItem('senior-client-language');
let currentLanguage = savedLanguage === 'en' ? 'en' : 'tr';

function applyLanguage(language) {
  const dictionary = translations[language];

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const translation = dictionary[element.dataset.i18n];
    if (translation === undefined) return;

    if (element.dataset.i18n.includes('Btn') || element.dataset.i18n === 'download.button' || element.dataset.i18n === 'hero.title') {
      element.innerHTML = translation;
    } else {
      element.textContent = translation;
    }
  });

  document.documentElement.lang = language;
  description.content = dictionary['meta.description'];
  languageButton.querySelector('span').textContent = language.toUpperCase();
  languageButton.setAttribute('aria-label', language === 'tr' ? 'Switch language to English' : 'Dili Türkçeye değiştir');
  localStorage.setItem('senior-client-language', language);
}

languageButton.addEventListener('click', () => {
  currentLanguage = currentLanguage === 'tr' ? 'en' : 'tr';
  applyLanguage(currentLanguage);
});

applyLanguage(currentLanguage);
